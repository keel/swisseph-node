#!/usr/bin/env node
/**
 * Convert prebuilds/<platform>/swisseph-node.node into base64 JS modules under
 * lib/b64/<platform>.js, so bundlers (esbuild & friends) can inline the binary
 * into a single-file bundle. Platforms without a local prebuild get a null
 * placeholder (required — esbuild fails on missing static requires); CI matrix
 * builds overwrite them with real payloads before publishing.
 *
 * Run after `npm run prebuild`. See .github/workflows/publish.yml.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const prebuildsDir = path.join(root, 'prebuilds');
const b64Dir = path.join(root, 'lib', 'b64');
const PLATFORMS = ['linux-x64', 'linux-arm64', 'darwin-x64', 'darwin-arm64'];

fs.mkdirSync(b64Dir, { recursive: true });

let real = 0;
for (const plat of PLATFORMS) {
  const nodeFile = path.join(prebuildsDir, plat, 'swisseph-node.node');
  const out = path.join(b64Dir, plat + '.js');
  if (fs.existsSync(nodeFile)) {
    const buf = fs.readFileSync(nodeFile);
    fs.writeFileSync(out, `// Auto-generated by scripts/gen-b64.js — binary of swisseph_node for ${plat}.\nmodule.exports = ${JSON.stringify(buf.toString('base64'))};\n`);
    console.log(`gen-b64: ${plat} ${(buf.length / 1024).toFixed(0)}KB (real)`);
    real++;
  } else if (!fs.existsSync(out)) {
    fs.writeFileSync(out, `// Placeholder for ${plat} — replaced by a real payload when built on that platform.\nmodule.exports = null;\n`);
    console.log(`gen-b64: ${plat} placeholder`);
  }
}
if (!real) {
  console.error('gen-b64: no prebuilds found — run `npm run prebuild` first');
  process.exit(1);
}
